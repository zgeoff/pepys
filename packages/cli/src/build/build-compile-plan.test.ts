import { expect, test } from 'bun:test';
import { defineConsumer } from '@pepys/kit';
import { buildCompilePlan } from './build-compile-plan.ts';

function setupTest() {
  return {
    buildConsumer: (entry: string) =>
      defineConsumer({
        name: 'tide_log',
        entry: new URL(entry),
        input: { mode: 'fact', streams: [] },
        tables: {},
        entityViews: [],
        reads: [],
        links: [],
      }),
  };
}

test.each([
  [
    'an entry in no package',
    'file:///harbour/src/consumers/tide-log.ts',
    undefined,
    'the entry /harbour/src/consumers/tide-log.ts is in no package',
  ],
  [
    'an entry outside the src folder of its package',
    'file:///harbour/scripts/tide-log.ts',
    '/harbour',
    'the entry /harbour/scripts/tide-log.ts is outside the src folder of its package',
  ],
])('it refuses %s', (_title, entry, packageRoot, failure) => {
  const ctx = setupTest();

  const plan = buildCompilePlan({
    consumer: ctx.buildConsumer(entry),
    families: [],
    settings: undefined,
    out: '/harbour/build',
    packageRoot,
  });

  expect(plan).toStrictEqual({ ok: false, failure });
});

test('it plans the work folder, the glue in its copy of src, the profile and the module', () => {
  const ctx = setupTest();

  const plan = buildCompilePlan({
    consumer: ctx.buildConsumer('file:///harbour/src/consumers/tide-log.ts'),
    families: [],
    settings: undefined,
    out: '/harbour/build',
    packageRoot: '/harbour',
  });

  expect(plan).toStrictEqual({
    ok: true,
    value: {
      source: '/harbour/src',
      work: '/harbour/build/.work/tide_log',
      files: [
        {
          path: '/harbour/build/.work/tide_log/src/generated/tide-log-boundary.ts',
          content: expect.stringMatching(/^\/\/ Generated by `pepys build`\./u),
        },
        {
          path: '/harbour/build/.work/tide_log/src/generated/tide-log.sql',
          content: expect.stringMatching(/^-- Generated by `pepys build`\./u),
        },
        {
          path: '/harbour/build/.work/tide_log/profile.json',
          content: expect.stringContaining('"src/consumers/tide-log.ts"'),
        },
      ],
      modulePath: '/harbour/build/.work/tide_log/module.wasm',
    },
  });
});
