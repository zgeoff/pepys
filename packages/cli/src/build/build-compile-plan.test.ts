import { expect, test } from 'bun:test';
import { defineConsumer, defineTable } from '@pepys/kit';
import { buildCompilePlan } from './build-compile-plan.ts';
import { consumerFences } from './consumer-fences.ts';

function setupTest() {
  return {
    buildConsumer: (entry: string) =>
      defineConsumer({
        name: 'tide_log',
        entry: new URL(entry),
        input: { mode: 'fact', streams: [] },
        tables: {},
        entityViews: [],
        reads: [],
        links: [],
      }),
  };
}

test.each([
  [
    'an entry in no package',
    'file:///harbour/src/consumers/tide-log.ts',
    undefined,
    'the entry /harbour/src/consumers/tide-log.ts is in no package',
  ],
  [
    'an entry outside the src folder of its package',
    'file:///harbour/scripts/tide-log.ts',
    '/harbour',
    'the entry /harbour/scripts/tide-log.ts is outside the src folder of its package',
  ],
])('it refuses %s', (_title, entry, packageRoot, failure) => {
  const ctx = setupTest();

  const plan = buildCompilePlan({
    consumer: ctx.buildConsumer(entry),
    families: [],
    settings: undefined,
    out: '/harbour/build',
    packageRoot,
  });

  expect(plan).toStrictEqual({ ok: false, failure });
});

