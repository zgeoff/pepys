import { fileURLToPath } from 'node:url';
import type { ConsumerDeclaration, FactFamily, SettingValue } from '@pepys/kit';
import { generateBoundaryGlue, generateSqliteSchema } from '@pepys/kit/generators';

export interface GlueFile {
  // an absolute path
  path: string;
  content: string;
}

export interface ConsumerGlueParameters {
  consumer: ConsumerDeclaration;
  families: readonly FactFamily[];

  // the checked settings of the consumer's plug-in, or undefined when it declares none
  settings: Readonly<Record<string, SettingValue>> | undefined;
}

// The glue of a consumer sits in the `generated` folder beside the folder of its entry file:
// `<consumer>-boundary.ts` and `<consumer>.sql`.
export function buildConsumerGlue(parameters: ConsumerGlueParameters): GlueFile[] {
  const consumer = parameters.consumer;
  const stem = consumer.name.replaceAll('_', '-');

  const folder = new URL('../generated/', consumer.entry);

  return [
    {
      path: fileURLToPath(new URL(`${stem}-boundary.ts`, folder)),
      content: formatWithHeader(
        '//',
        generateBoundaryGlue({
          consumer,
          families: parameters.families,
          settings: parameters.settings,
        }),
      ),
    },
    {
      path: fileURLToPath(new URL(`${stem}.sql`, folder)),
      content: formatWithHeader('--', generateSqliteSchema(consumer)),
    },
  ];
}

function formatWithHeader(comment: '//' | '--', body: string): string {
  return `${comment} Generated by \`pepys build\`. Do not edit.\n\n${body}`;
}
