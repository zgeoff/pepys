import { expect, test } from 'bun:test';
import { generateBoundaryGlue } from '@pepys/kit/generators';
import invariant from 'tiny-invariant';
import { createTestStore } from '../test-store/create-test-store.ts';
import { parseAppliedFacts } from '../test-store/parse-applied-facts.ts';
import type { AppliedFact } from '../test-store/types.ts';
import journey from './dock-journey.json' with { type: 'json' };
import { dockBerthConsumer, dockPlugin, dockSource } from './dock-plugin.ts';

// The Rust e2e lane runs the journey's records through the compiled dock module, on two streams,
// and expects its rows. The arrivals are on one stream and the loads on the other, and the times
// interleave, so the order that the scope reads in is the order of the merge by time.

function setupTest() {
  const facts: AppliedFact<typeof dockSource>[] = [
    {
      type: 'dock.arrival.logged',
      event: 'evt-1',
      entity: 'dock:berth:a',
      at: '2026-11-01T09:00:00Z',
      payload: { vessel: 'Heron' },
    },
    {
      type: 'dock.load.weighed',
      event: 'evt-2',
      entity: 'dock:berth:a',
      at: '2026-11-01T09:30:00Z',
      payload: { tonnes: 5 },
    },
    {
      type: 'dock.arrival.logged',
      event: 'evt-3',
      entity: 'dock:berth:b',
      at: '2026-11-01T09:40:00Z',
      payload: { vessel: 'Wren' },
    },
    {
      type: 'dock.load.weighed',
      event: 'evt-4',
      entity: 'dock:berth:b',
      at: '2026-11-01T09:45:00Z',
      payload: { tonnes: 7 },
    },
    {
      type: 'dock.arrival.logged',
      event: 'evt-5',
      entity: 'dock:berth:a',
      at: '2026-11-01T10:00:00Z',
      payload: { vessel: 'Kestrel' },
    },
    {
      type: 'dock.load.weighed',
      event: 'evt-6',
      entity: 'dock:berth:a',
      at: '2026-11-01T10:30:00Z',
      payload: { tonnes: 3 },
    },
  ];

  return { facts };
}

test('it commits the glue that the kit generates for the dock consumer', async () => {
  const committed = await Bun.file(
    new URL('generated/dock-berth-boundary.ts', import.meta.url),
  ).text();

  const glue = generateBoundaryGlue({
    consumer: dockBerthConsumer,
    families: dockSource.families,
    settings: undefined,
  });

  expect(committed).toBe(`// Generated by \`pepys build\`. Do not edit.\n\n${glue}`);
});

test('it holds the records that ingest stores for the facts of the dock journey', () => {
  const ctx = setupTest();
  const parsed = parseAppliedFacts(dockSource, ctx.facts, undefined);

  invariant(parsed.ok, 'a fact of the dock journey failed to parse');

  const records = parsed.value.map((fact) => ({
    stream: fact.stream,
    body: JSON.stringify(fact.envelope),
  }));

  expect(records).toStrictEqual(journey.records);
});

test('it holds the rows that the test store gives a scope that spans two streams', async () => {
  const ctx = setupTest();

  await using store = await createTestStore({ plugins: [dockPlugin] });

  await store.apply(dockSource, ctx.facts);

  const received: unknown = {
    rows: { dock_berth: await store.readRows('dock_berth') },
    links: await store.readLinks(),
  };

  expect(received).toStrictEqual({ rows: journey.rows, links: journey.links });
});
