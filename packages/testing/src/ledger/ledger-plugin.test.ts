import { expect, test } from 'bun:test';
import { generateBoundaryGlue } from '@pepys/kit/generators';
import { ledgerAccountConsumer, ledgerSource } from './ledger-plugin.ts';

test('it commits the glue that the kit generates for the ledger consumer', async () => {
  const committed = await Bun.file(
    new URL('generated/ledger-account-boundary.ts', import.meta.url),
  ).text();

  const glue = generateBoundaryGlue({
    consumer: ledgerAccountConsumer,
    families: ledgerSource.families,
    settings: undefined,
  });

  expect(committed).toBe(`// Generated by \`pepys build\`. Do not edit.\n\n${glue}`);
});
