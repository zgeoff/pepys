import { join, relative } from 'node:path';
import { checkBuildTarget, collectGlueFiles } from '@pepys/cli';
import type { DeploymentFailure } from '@pepys/kit';
import { generateKyselyTypes } from '@pepys/schema';
import { e2eDeployment } from '../packages/cli/e2e/fixtures/e2e-deployment.ts';
import { stubDeployment } from './stub-deployment.ts';

export interface GeneratedFile {
  path: string;
  content: string;
}

export type GeneratedFiles =
  | { ok: true; files: GeneratedFile[] }
  | { ok: false; failures: readonly DeploymentFailure[] };

const root = join(import.meta.dir, '..');

export function buildGeneratedFiles(): GeneratedFiles {
  const target = checkBuildTarget({ kind: 'deployment', deployment: stubDeployment });

  if (!target.ok) {
    return { ok: false, failures: target.failure };
  }

  // The e2e deployment holds the stub's plug-ins and more, so only the glue of its other consumers
  // comes from it.
  const laneTarget = checkBuildTarget({ kind: 'deployment', deployment: e2eDeployment });

  if (!laneTarget.ok) {
    return { ok: false, failures: laneTarget.failure };
  }

  const consumers = target.value.checked.consumers;

  // the glue files come from the same code as `pepys build`
  const stubGlue = collectGlueFiles({ target: target.value, packageRoot: join(root, 'packages') });

  const stubPaths = new Set(stubGlue.map((file) => file.path));

  const glue = [
    ...stubGlue,
    ...collectGlueFiles({ target: laneTarget.value, packageRoot: root }).filter(
      (file) => !stubPaths.has(file.path),
    ),
  ];

  return {
    ok: true,
    files: [
      {
        path: 'packages/schema/src/generated/kysely-db.ts',
        content: formatWithHeader('//', generateKyselyTypes(consumers)),
      },
      ...glue.map((file) => ({ path: relative(root, file.path), content: file.content })),
    ],
  };
}

function formatWithHeader(comment: '//' | '--', body: string): string {
  return `${comment} Generated by \`bun run schema:generate\`. Do not edit.\n\n${body}`;
}
