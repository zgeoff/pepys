import {
  checkConsumers,
  generateBoundaryGlue,
  generateKyselyTypes,
  generateRustTypes,
  generateSqliteSchema,
} from '@pepys/schema';
import type { ConsumerDeclaration, ConsumerFailure } from '@pepys/schema';
import { consumerSources } from './consumer-sources.ts';

export interface GeneratedFile {
  path: string;
  content: string;
}

export type GeneratedFiles =
  | { ok: true; files: GeneratedFile[] }
  | { ok: false; failures: ConsumerFailure[] };

export function buildGeneratedFiles(): GeneratedFiles {
  const consumers: ConsumerDeclaration[] = consumerSources.flatMap((source) => source.consumers);
  const check = checkConsumers(consumers);

  if (!check.ok) {
    return check;
  }

  const sourceFiles = consumerSources.flatMap((source) =>
    source.consumers.flatMap((consumer) => {
      const stem = `${source.directory}/src/generated/${consumer.name.replaceAll('_', '-')}`;

      return [
        {
          path: `${stem}-boundary.ts`,
          content: withHeader('//', generateBoundaryGlue({ consumer, consumers })),
        },
        { path: `${stem}.sql`, content: withHeader('--', generateSqliteSchema(consumer)) },
      ];
    }),
  );

  return {
    ok: true,
    files: [
      {
        path: 'packages/schema/src/generated/kysely-db.ts',
        content: withHeader('//', generateKyselyTypes(consumers)),
      },
      ...sourceFiles,
      {
        path: 'crates/schema/src/generated.rs',
        content: withHeader('//', generateRustTypes(consumers)),
      },
    ],
  };
}

function withHeader(comment: '//' | '--', body: string): string {
  return `${comment} Generated by \`bun run schema:generate\`. Do not edit.\n\n${body}`;
}
